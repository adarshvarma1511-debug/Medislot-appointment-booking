export const generateTimeSlots = (doctorId, date) => {
  const baseSlots = [
    "10:00 AM",
    "10:30 AM",
    "11:00 AM",
    "11:30 AM",
    "12:00 PM",
    "12:30 PM",
  ]
  const bookedIndices = doctorId === "d1" ? [1, 4] : [0, 3]
  return baseSlots.map((time, i) => ({
    time,
    status: bookedIndices.includes(i) ? "booked" : "available",
  }))
}

